#!/usr/bin/env python3
"""Generate the requirements file the pex binary is built from, out of uv.lock.

The pex bundles the runtime dependency closure of ``internetarchive``. Before
this script existed that closure came from a hand-written file of version
floors, so the binary carried whatever PyPI served on build day: the 5.12.0
pex shipped certifi 2026.7.22 a week after 2026.10.19 removed a compromised
root CA. uv.lock is the one place dependency versions are pinned and reviewed,
so the pex inputs are derived from it rather than maintained beside it.

Each dependency is emitted as a direct URL to its universal
(``py3-none-any``) wheel with the sha256 recorded in the lockfile, so pip runs
in hash-checking mode and the pex is reproducible from the lockfile alone.
Requiring a universal wheel is also what keeps the pex itself universal: the
day a dependency stops publishing one, this script fails instead of pip
silently selecting the build machine's platform wheel.

pip's hash-checking mode cannot verify a source directory, so the project
itself goes in as a prebuilt wheel: pass its path and it is appended with a
sha256 computed on the spot.

Usage::

    uv build --wheel -o build/pex
    python3 tools/pex_requirements.py build/pex/internetarchive-*.whl \
        > pex-requirements.txt

Only the standard library is used (``tomli`` is imported as a fallback on
Python 3.10, where ``tomllib`` does not exist yet).
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib  # type: ignore[import-not-found,no-redef]

ROOT_PACKAGE = 'internetarchive'
UNIVERSAL_SUFFIX = '-none-any.whl'


def runtime_closure(packages: dict[str, dict]) -> dict[str, set[str | None]]:
    """Walk the lockfile's ``dependencies`` edges from the root package.

    Extras and dependency groups live under separate keys in ``uv.lock``
    (``optional-dependencies``, ``dev-dependencies``), so following only
    ``dependencies`` yields exactly the runtime closure.

    :param packages: Lockfile ``[[package]]`` tables keyed by name.
    :returns: Each reached package name mapped to the set of environment
              markers on the edges that reached it. ``None`` in the set means
              at least one edge is unconditional.
    """
    reached: dict[str, set[str | None]] = {}
    stack = [ROOT_PACKAGE]
    while stack:
        name = stack.pop()
        for dep in packages[name].get('dependencies', []):
            dep_name = dep['name']
            markers = reached.setdefault(dep_name, set())
            first_visit = not markers
            markers.add(dep.get('marker'))
            if first_visit:
                stack.append(dep_name)
    return reached


def universal_wheel(package: dict) -> dict:
    """Pick the one wheel that installs on any platform and Python 3.

    :param package: A lockfile ``[[package]]`` table.
    :returns: The ``wheels`` entry whose filename ends in ``-none-any.whl``.
    :raises SystemExit: If the package publishes no universal wheel.
    """
    wheels = [
        w for w in package.get('wheels', []) if w['url'].endswith(UNIVERSAL_SUFFIX)
    ]
    if len(wheels) != 1:
        sys.exit(
            f"{package['name']} {package['version']}: expected exactly one "
            f"universal wheel in uv.lock, found {len(wheels)}. The pex can no "
            "longer be built as a single universal binary from this lockfile."
        )
    return wheels[0]


def project_wheel_line(wheel_path: Path) -> str:
    """Pin the locally built project wheel by path and content hash.

    :param wheel_path: A wheel built from this checkout, e.g. by ``uv build``.
    :returns: A requirements line pip can verify in hash-checking mode.
    :raises SystemExit: If the path is not a wheel file.
    """
    if not (wheel_path.is_file() and wheel_path.suffix == '.whl'):
        sys.exit(f'{wheel_path}: not a wheel file')
    digest = hashlib.sha256(wheel_path.read_bytes()).hexdigest()
    return f'{ROOT_PACKAGE} @ {wheel_path.resolve().as_uri()} --hash=sha256:{digest}'


def main() -> None:
    """Print a hash-pinned requirements file for the pex build to stdout.

    The optional first argument is the project's own wheel; without it the
    output covers dependencies only.
    """
    lock_path = Path(__file__).resolve().parent.parent / 'uv.lock'
    with lock_path.open('rb') as fh:
        lock = tomllib.load(fh)
    packages = {p['name']: p for p in lock['package']}

    print('# Generated by tools/pex_requirements.py from uv.lock. Do not edit;')
    print('# change pyproject.toml / uv.lock and rebuild instead.')
    for name, markers in sorted(runtime_closure(packages).items()):
        package = packages[name]
        wheel = universal_wheel(package)
        line = f"{name} @ {wheel['url']}"
        if None not in markers:
            line += ' ; ' + ' or '.join(sorted(f'({m})' for m in markers if m))
        print(f"{line} --hash={wheel['hash']}")
    if len(sys.argv) > 1:
        print(project_wheel_line(Path(sys.argv[1])))


if __name__ == '__main__':
    main()
